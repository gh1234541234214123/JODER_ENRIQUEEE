function split_sql(string $sql): array
{
    $lines = preg_split('/\r\n|\r|\n/', $sql);
    $clean = [];
    foreach ($lines as $line) {
        $trim = ltrim($line);
        if (strncmp($trim, '--', 2) === 0 || strncmp($trim, '#', 1) === 0) {
            continue;
        }
        $clean[] = $line;
    }
    $sql   = implode("\n", $clean);
    $parts = array_map('trim', explode(';', $sql));

    return array_values(array_filter($parts, static function ($s) {
        if ($s === '') {
            return false;
        }
        // The schema begins with "create database ..." / "use ..." for manual
        // imports; skip them so the installer honours the entered database name.
        $lower = strtolower($s);
        if (strncmp($lower, 'use ', 4) === 0 || strncmp($lower, 'create database', 15) === 0) {
            return false;
        }
        return true;
    }));
}

$errors = [];
$done   = false;

$host      = (string) ($_POST['host'] ?? 'localhost');
$name      = (string) ($_POST['name'] ?? 'joder');
$user      = (string) ($_POST['user'] ?? 'root');
$pass      = (string) ($_POST['pass'] ?? '');
$siteName  = (string) ($_POST['site_name'] ?? 'JODER_ENRIQUEEE');
$favLetter = (string) ($_POST['fav_letter'] ?? '');
$favColor  = (string) ($_POST['fav_color'] ?? '#4f46e5');
$favShape  = (string) ($_POST['fav_shape'] ?? 'rounded');
$createDb  = isset($_POST['create_db']);

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $host = trim($host);
    $name = trim($name);
    $user = trim($user);
    $siteName = trim($siteName);
    if ($siteName === '') {
        $siteName = 'JODER_ENRIQUEEE';
    }
    $favLetter = trim($favLetter);
    if ($favLetter === '') {
        $favLetter = favicon_letter($siteName);
    }
    $favColor = favicon_hex($favColor);
    $favShape = favicon_shape($favShape);

    if ($host === '' || $name === '' || $user === '') {
        $errors[] = 'Host, base de datos y usuario son obligatorios.';
    }
    if ($name !== '' && !preg_match('/^[A-Za-z0-9_]+$/', $name)) {
        $errors[] = 'El nombre de la base de datos solo puede contener letras, números y guiones bajos.';
    }
    if (!is_file($schemaFile)) {
        $errors[] = 'No se encontró schema.sql en la raíz del proyecto.';
    }

    if (!is_dir($configDir)) {
        @mkdir($configDir, 0775, true);
    }
    if (!is_dir($configDir) || !is_writable($configDir)) {
        $errors[] = 'El directorio config/ no existe o no tiene permisos de escritura.';
    }

    if (!$errors) {
        $options = [
            PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            PDO::ATTR_EMULATE_PREPARES   => false,
        ];

        try {
            if ($createDb) {
                $serverPdo = new PDO('mysql:host=' . $host . ';charset=utf8mb4', $user, $pass, $options);
                $serverPdo->exec(
                    'CREATE DATABASE IF NOT EXISTS `' . $name . '` '
                    . 'CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci'
                );
                $serverPdo = null;
            }

            $pdo = new PDO('mysql:host=' . $host . ';dbname=' . $name . ';charset=utf8mb4', $user, $pass, $options);

            foreach (split_sql((string) file_get_contents($schemaFile)) as $statement) {
                $pdo->exec($statement);
            }

            $config = [
                'local' => [
                    'db'        => ['host' => $host, 'name' => $name, 'user' => $user, 'pass' => $pass],
                    'debug'     => true,
                    'site_name' => $siteName,
                    'session_driver' => 'database',
                ],
                'production' => [
                    'db'        => ['host' => $host, 'name' => $name, 'user' => $user, 'pass' => $pass],
                    'debug'     => false,
                    'site_name' => $siteName,
                    'session_driver' => 'database',
                ],
            ];

            $php = "<?php\n"
                . "// Generated by setup.php on " . date('c') . ". Private - do not commit.\n"
                . "return " . var_export($config, true) . ";\n";

            if (@file_put_contents($configFile, $php) === false) {
                $errors[] = 'No se pudo escribir config/config.php.';
            } else {
                $done = true;

                $favFiles = [];
                if (!empty($_FILES['fav_image']['name'] ?? '')) {
                    try {
                        $favFiles = favicon_upload($root, $_FILES['fav_image']);
                    } catch (RuntimeException $e) {
                        $favFiles = [];
                    }
                }
                if (!$favFiles) {
                    favicon_write($root, $favLetter, $favColor, $favShape);
                }
            }
        } catch (PDOException $e) {
            $errors[] = 'Error de conexión o creación de la base de datos: ' . $e->getMessage();
        }
    }
}

function h(?string $v): string
{
    return htmlspecialchars((string) $v, ENT_QUOTES);
}
